-- 1. Create Books Table
CREATE TABLE IF NOT EXISTS public.books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  author TEXT NOT NULL,
  isbn TEXT UNIQUE NOT NULL,
  category TEXT NOT NULL,
  total_copies INT NOT NULL DEFAULT 1 CHECK (total_copies >= 0),
  available_copies INT NOT NULL DEFAULT 1 CHECK (available_copies >= 0),
  shelf_location TEXT NOT NULL,
  publication_year INT NOT NULL,
  description TEXT NOT NULL,
  cover_icon TEXT NOT NULL DEFAULT '📚',
  rating NUMERIC(2,1) NOT NULL DEFAULT 4.8,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Profiles Table (Linked to Supabase Auth users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL,
  member_id TEXT UNIQUE NOT NULL,
  role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('member', 'admin')),
  department TEXT DEFAULT 'General',
  wallet_balance NUMERIC(10,2) NOT NULL DEFAULT 25.00 CHECK (wallet_balance >= 0),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Borrow Records Table
CREATE TABLE IF NOT EXISTS public.borrow_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  book_id BIGINT NOT NULL REFERENCES public.books(id) ON DELETE CASCADE,
  borrow_date DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date DATE NOT NULL DEFAULT (CURRENT_DATE + INTERVAL '14 days'),
  return_date DATE DEFAULT NULL,
  status TEXT NOT NULL DEFAULT 'borrowed' CHECK (status IN ('borrowed', 'returned', 'overdue')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3b. Create Wallet Transactions Table
CREATE TABLE IF NOT EXISTS public.wallet_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  amount NUMERIC(10,2) NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('topup', 'fine_payment', 'service_fee')),
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Automatically create a profile when a new user signs up in Supabase Auth
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  v_random_id TEXT;
BEGIN
  v_random_id := 'LIB-' || TO_CHAR(NOW(), 'YYYY') || '-' || LPAD(FLOOR(RANDOM() * 900 + 100)::TEXT, 3, '0');
  
  INSERT INTO public.profiles (id, name, email, member_id, role, department)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
    NEW.email,
    v_random_id,
    COALESCE(NEW.raw_user_meta_data->>'role', 'member'),
    COALESCE(NEW.raw_user_meta_data->>'department', 'General')
  )
  ON CONFLICT (id) DO NOTHING;
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 5. Atomic Borrow Book Function
CREATE OR REPLACE FUNCTION public.borrow_book(p_book_id BIGINT, p_user_id UUID)
RETURNS JSONB AS $$
DECLARE
  v_book RECORD;
  v_active_count INT;
  v_already_borrowed BOOLEAN;
  v_record_id BIGINT;
  v_due_date DATE;
BEGIN
  -- Check active loan count (max 5)
  SELECT COUNT(*) INTO v_active_count 
  FROM public.borrow_records 
  WHERE user_id = p_user_id AND status = 'borrowed';

  IF v_active_count >= 5 THEN
    RAISE EXCEPTION 'Borrowing limit reached: Maximum 5 books can be checked out concurrently';
  END IF;

  -- Check if user already borrowed this book
  SELECT EXISTS(
    SELECT 1 FROM public.borrow_records 
    WHERE user_id = p_user_id AND book_id = p_book_id AND status = 'borrowed'
  ) INTO v_already_borrowed;

  IF v_already_borrowed THEN
    RAISE EXCEPTION 'You already have an active loan for this book';
  END IF;

  -- Check book availability and lock the row
  SELECT * INTO v_book FROM public.books WHERE id = p_book_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Book not found';
  END IF;

  IF v_book.available_copies <= 0 THEN
    RAISE EXCEPTION 'No copies currently available to borrow';
  END IF;

  -- Decrement copy count
  UPDATE public.books 
  SET available_copies = available_copies - 1 
  WHERE id = p_book_id;

  -- Insert loan record
  v_due_date := CURRENT_DATE + INTERVAL '14 days';
  INSERT INTO public.borrow_records (user_id, book_id, borrow_date, due_date, status)
  VALUES (p_user_id, p_book_id, CURRENT_DATE, v_due_date, 'borrowed')
  RETURNING id INTO v_record_id;

  RETURN jsonb_build_object(
    'record_id', v_record_id,
    'book_id', p_book_id,
    'book_title', v_book.title,
    'borrow_date', CURRENT_DATE,
    'due_date', v_due_date
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 6. Atomic Return Book Function
CREATE OR REPLACE FUNCTION public.return_book(p_record_id BIGINT, p_user_id UUID)
RETURNS JSONB AS $$
DECLARE
  v_record RECORD;
BEGIN
  SELECT * INTO v_record 
  FROM public.borrow_records 
  WHERE id = p_record_id AND user_id = p_user_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Loan record not found or does not belong to user';
  END IF;

  IF v_record.status = 'returned' THEN
    RAISE EXCEPTION 'This book has already been returned';
  END IF;

  -- Update loan status
  UPDATE public.borrow_records 
  SET return_date = CURRENT_DATE, status = 'returned' 
  WHERE id = p_record_id;

  -- Increment book copy
  UPDATE public.books 
  SET available_copies = available_copies + 1 
  WHERE id = v_record.book_id;

  RETURN jsonb_build_object(
    'success', true,
    'record_id', p_record_id,
    'book_id', v_record.book_id,
    'return_date', CURRENT_DATE
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 7. Row Level Security (RLS) Policies
ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.borrow_records ENABLE ROW LEVEL SECURITY;

-- Books: readable by everyone, modifiable by admin or service role
CREATE POLICY "Books are viewable by everyone" ON public.books
  FOR SELECT USING (true);

CREATE POLICY "Admins can insert books" ON public.books
  FOR INSERT WITH CHECK (
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

CREATE POLICY "Admins can update books" ON public.books
  FOR UPDATE USING (
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Profiles: users can view and update their own, admins can view all
CREATE POLICY "Users can view own profile or admins can view all" ON public.profiles
  FOR SELECT USING (
    auth.uid() = id OR 
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

CREATE POLICY "Users can update own profile" ON public.profiles
  FOR UPDATE USING (auth.uid() = id);

-- Borrow records: users can view their own, admins can view all
CREATE POLICY "Users can view own borrow records" ON public.borrow_records
  FOR SELECT USING (
    auth.uid() = user_id OR 
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

-- Wallet transactions: users can view own transactions, admins can view all
ALTER TABLE public.wallet_transactions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view own wallet transactions" ON public.wallet_transactions
  FOR SELECT USING (
    auth.uid() = user_id OR 
    EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin')
  );

CREATE POLICY "Users can insert own wallet transactions" ON public.wallet_transactions
  FOR INSERT WITH CHECK (auth.uid() = user_id);

